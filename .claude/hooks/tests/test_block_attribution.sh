#!/usr/bin/env bash
# Tests for the block-attribution.sh hook.
# shellcheck source=.method/scripts/tests/lib.sh
source "$(dirname "$0")/../../../.method/scripts/tests/lib.sh"
HOOK="$REPO/.claude/hooks/block-attribution.sh"

run() { jq -cn --arg c "$1" --arg d "$REPO" '{tool_input: {command: $c}, cwd: $d}' | "$HOOK"; }

trailer="Co-Authored-By: Claude <noreply@anthropic.com>"
assert_status 2 "blocks trailer in commit" run "git commit -m \"feat: x

$trailer\""
assert_status 2 "blocks PR body signature" run 'gh pr create --title x --body "Generated with [Claude Code](https://claude.com/claude-code)"'
assert_status 2 "blocks issue comment signature" run 'gh issue comment 3 --body "🤖 Generated with Claude Code"'
printf 'Resumo\n\n%s\n' "$trailer" >"$TMP/body.md"
assert_status 2 "blocks signature inside --body-file" run "gh pr edit 3 --body-file $TMP/body.md"
assert_status 2 "blocks signature inside --body-file=" run "gh pr edit 3 --body-file=$TMP/body.md"
assert_status 2 "blocks gh -R repo pr create" run "gh -R owner/repo pr create --title x --body-file $TMP/body.md"
printf 'Resumo limpo\n' >"$TMP/clean.md"
assert_status 0 "allows clean --body-file" run "gh pr edit 3 --body-file $TMP/clean.md"
assert_status 0 "allows clean commit" run 'git commit -m "fix: clean message"'
assert_status 0 "ignores other commands" run "echo '$trailer'"
# One case per signature form.
assert_status 2 "blocks Generated by Claude" run 'gh pr comment 3 --body "Generated by Claude"'
assert_status 2 "blocks Generated by Claude in --body=" run 'gh pr create --title x --body="Resumo

Generated by Claude Code"'
assert_status 2 "blocks the emoji alone" run 'gh issue comment 3 --body "Feito.

🤖"'
assert_status 2 "blocks gh issue close --comment" run 'gh issue close 3 --comment "🤖 Generated with Claude Code"'
assert_status 2 "blocks gh pr close --comment" run "gh pr close 3 --comment \"$trailer\""
assert_status 2 "blocks a bare heredoc message" run "git commit -F - <<EOF
feat: x

Generated by Claude
EOF"
# Text that only cites the rule is not a signature.
assert_status 0 "allows citing the rule in an issue" run 'gh issue create --title "hook" --body "O hook barra \"Generated by Claude\", o trailer `Co-Authored-By:` e o emoji 🤖 sozinho."'
printf 'A regra 6 proíbe "Generated with Claude Code", `Co-Authored-By:` e o emoji 🤖.\n' >"$TMP/cite.md"
assert_status 0 "allows citing the rule in --body-file" run "gh pr edit 3 --body-file $TMP/cite.md"
assert_status 0 "allows citing the rule in a commit" run 'git commit -m "fix(hooks): block \"Generated by Claude\" and the 🤖 emoji alone"'
finish
