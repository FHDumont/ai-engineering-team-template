#!/usr/bin/env bash
# Tests of check-attribution.sh: an AI trailer must fail.
# shellcheck source=scripts/tests/lib.sh
source "$(dirname "$0")/lib.sh"
CHECK="$SCRIPTS/check-attribution.sh"

printf 'feat: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\n' >"$TMP/trailer.txt"
assert_status 1 "fails on Co-Authored-By trailer" "$CHECK" --text-file "$TMP/trailer.txt"
assert_contains "$(last_output)" "AI attribution" "reports the hit"
printf 'Resumo\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n' >"$TMP/pr.txt"
assert_status 1 "fails on PR signature" "$CHECK" --text-file "$TMP/pr.txt"
printf 'fix: keep clean history\n' >"$TMP/clean.txt"
assert_status 0 "passes clean text" "$CHECK" --text-file "$TMP/clean.txt"

printf 'Resumo\n\nGenerated by Claude\n' >"$TMP/by.txt"
assert_status 1 "fails on Generated by Claude" "$CHECK" --text-file "$TMP/by.txt"
printf 'Resumo\n\n🤖\n' >"$TMP/emoji.txt"
assert_status 1 "fails on the emoji alone" "$CHECK" --text-file "$TMP/emoji.txt"
printf 'A regra proíbe "Generated by Claude", `Co-Authored-By:` (noreply@anthropic.com) e o emoji 🤖.\n' >"$TMP/cite.txt"
assert_status 0 "passes text that only cites the rule" "$CHECK" --text-file "$TMP/cite.txt"

repo="$(make_repo)"
base="$(git -C "$repo" rev-parse HEAD)"
echo x >"$repo/x"; git -C "$repo" add x; git -C "$repo" commit --quiet -m "feat: clean"
assert_status 0 "passes clean range" sh -c "cd '$repo' && '$CHECK' --range $base..HEAD"
echo y >"$repo/y"; git -C "$repo" add y
git -C "$repo" commit --quiet -m "feat: signed" -m "Co-authored-by: Claude <noreply@anthropic.com>"
assert_status 1 "fails range with trailer (any case)" sh -c "cd '$repo' && '$CHECK' --range $base..HEAD"

cat >"$TMP/handler.sh" <<'H'
case "$*" in
  *"--json body"*) echo "Corpo limpo" ;;
  *"--json commits"*) printf 'feat: a\n\n' ;;
esac
H
use_fake_gh "$TMP/handler.sh"
assert_status 0 "passes clean PR" "$CHECK" --pr 7
finish
